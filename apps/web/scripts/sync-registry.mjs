#!/usr/bin/env node
// Turns the block registry (packages/blocks/dist/r) into data the website
// can prerender, and publishes the registry itself with the site:
//
//   src/generated/items/<name>.json  per-item page data (lazy-loaded chunks)
//   src/generated/catalog.ts         catalog, categories and chunk loaders
//   public/r/*.json                  the raw registry `ng-email add` downloads
//   public/static/*                  images the blocks reference
//
// Code is highlighted here (Shiki, light + dark via CSS variables) so no
// highlighter ships to the browser. The HTML tab shows a Prettier-formatted
// copy for reading; previews and "Copy HTML" use the exact rendered output.
import { existsSync } from 'node:fs';
import { cp, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';

import { format } from 'prettier';
import { createHighlighter } from 'shiki';

const web = resolve(import.meta.dirname, '..');
const registry = resolve(web, '../../packages/blocks/dist');
const generated = join(web, 'src/generated');
const PUBLIC_ASSET_BASE = 'https://yshashi.github.io/ng-email/static/';

if (!existsSync(join(registry, 'r/index.json'))) {
  console.error('✖ packages/blocks/dist/r is missing. Run "npm run build" at the repo root first.');
  process.exit(1);
}

const slug = (text) => text.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

const highlighter = await createHighlighter({
  themes: ['github-light', 'github-dark'],
  langs: ['angular-ts', 'html'],
});
const highlight = (code, lang) =>
  highlighter.codeToHtml(code, {
    lang,
    themes: { light: 'github-light', dark: 'github-dark' },
    defaultColor: false,
  });

const { items: index } = JSON.parse(await readFile(join(registry, 'r/index.json'), 'utf8'));

await rm(generated, { recursive: true, force: true });
await mkdir(join(generated, 'items'), { recursive: true });

const catalog = [];
for (const meta of index) {
  const item = JSON.parse(await readFile(join(registry, 'r', `${meta.name}.json`), 'utf8'));
  const source = item.files[0].content;
  // Relative to the page's <base href>, so images work locally and under /ng-email/.
  const html = item.preview.html.replaceAll(PUBLIC_ASSET_BASE, 'static/');
  const pretty = await format(item.preview.html, { parser: 'html', printWidth: 100, htmlWhitespaceSensitivity: 'ignore' });

  const entry = {
    name: meta.name,
    title: meta.title,
    description: meta.description,
    category: meta.category,
    categorySlug: slug(meta.category),
    kind: meta.kind,
    className: meta.className,
    selector: meta.selector,
    fileName: item.files[0].path,
  };
  catalog.push(entry);

  await writeFile(
    join(generated, 'items', `${meta.name}.json`),
    JSON.stringify({
      ...entry,
      source,
      sourceHighlighted: highlight(source, 'angular-ts'),
      html,
      htmlOriginal: item.preview.html,
      htmlHighlighted: highlight(pretty, 'html'),
      text: item.preview.text,
      htmlBytes: Buffer.byteLength(item.preview.html),
    }),
  );
}

const categories = [];
for (const entry of catalog) {
  let category = categories.find((c) => c.kind === entry.kind && c.slug === entry.categorySlug);
  if (!category) {
    category = { kind: entry.kind, name: entry.category, slug: entry.categorySlug, items: [] };
    categories.push(category);
  }
  category.items.push(entry.name);
}

const loaders = catalog
  .map((e) => `  '${e.name}': () => import('./items/${e.name}.json').then((m) => m.default as SiteItem),`)
  .join('\n');

await writeFile(
  join(generated, 'catalog.ts'),
  `// Generated by scripts/sync-registry.mjs. Do not edit.
import type { CatalogEntry, Category, SiteItem } from '../app/registry.types';

export const catalog: CatalogEntry[] = ${JSON.stringify(catalog, null, 2)};

export const categories: Category[] = ${JSON.stringify(categories, null, 2)};

export const loaders: Record<string, () => Promise<SiteItem>> = {
${loaders}
};
`,
);

// ---- home page snippets ----------------------------------------------------
const componentSnippet = `@Component({
  selector: 'welcome-email',
  imports: [EMAIL_COMPONENTS],
  template: \`
    <html ngeHtml>
      <body ngeBody>
        <table ngeContainer>
          <h1 ngeHeading>Welcome, {{ name() }}</h1>
          <a ngeButton [href]="url()"
             [ngeStyle]="{ padding: '12px 20px' }">Open dashboard</a>
        </table>
      </body>
    </html>\`,
})
export class WelcomeEmail {
  readonly name = input.required<string>();
  readonly url = input.required<string>();
}`;
const renderSnippet = `const { html, text } = await renderEmailBoth(WelcomeEmail, {
  inputs: { name: 'Ada', url: 'https://acme.dev/app' },
});`;
// Real output: the button from the button-full block, as ng-email rendered it.
const buttonBlock = JSON.parse(await readFile(join(registry, 'r', 'button-full.json'), 'utf8'));
const buttonHtml = /<a [^>]*>[\s\S]*?<\/a>/.exec(buttonBlock.preview.html)?.[0] ?? '';
const outputSnippet = await format(buttonHtml, { parser: 'html', printWidth: 72, htmlWhitespaceSensitivity: 'ignore' });

await writeFile(
  join(generated, 'snippets.ts'),
  `// Generated by scripts/sync-registry.mjs. Do not edit.
export const snippets = ${JSON.stringify(
    {
      component: highlight(componentSnippet, 'angular-ts'),
      render: highlight(renderSnippet, 'angular-ts'),
      output: highlight(outputSnippet.trim(), 'html'),
    },
    null,
    2,
  )};
`,
);

await rm(join(web, 'public/r'), { recursive: true, force: true });
await cp(join(registry, 'r'), join(web, 'public/r'), { recursive: true });
await rm(join(web, 'public/static'), { recursive: true, force: true });
if (existsSync(join(registry, 'static'))) await cp(join(registry, 'static'), join(web, 'public/static'), { recursive: true });

const blocks = catalog.filter((e) => e.kind === 'block').length;
console.log(`✔ Synced ${blocks} blocks and ${catalog.length - blocks} templates in ${categories.length} categories`);
